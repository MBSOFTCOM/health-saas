-- DDL：表结构（若不存在则创建）
CREATE TABLE IF NOT EXISTS `expert_guidance_plan` (
  `id`                BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `plan_code`         VARCHAR(64)  NOT NULL COMMENT '方案编码（唯一）',
  `plan_name`         VARCHAR(128) NOT NULL COMMENT '方案名称',
  `age_months_min`    INT          NOT NULL COMMENT '适用最小月龄',
  `age_months_max`    INT          NOT NULL COMMENT '适用最大月龄',
  `applicable_gender` TINYINT      NOT NULL DEFAULT 0 COMMENT '适用性别 0全部 1男 2女',
  `guidance_category` VARCHAR(32)  NOT NULL COMMENT '指导维度 NUTRITION/GROWTH/PSYCHOLOGY/SAFETY/DISEASE/ORAL',
  `age_node`          VARCHAR(32)  NOT NULL COMMENT '月龄节点 NEONATAL/M1/M3/M6/M9/M12/M15/M18/M24/M30/M36/HIGH_RISK',
  `guidance_content`  TEXT         NOT NULL COMMENT '指导内容（详细文字）',
  `key_points`        TEXT         NULL     COMMENT '关键要点（JSON数组）',
  `warning_signs`     TEXT         NULL     COMMENT '预警症状（JSON数组）',
  `follow_up_advice`  VARCHAR(255) NULL     COMMENT '随访建议',
  `reference_source` VARCHAR(64)  NOT NULL DEFAULT '国家基本公共卫生服务规范(第三版)' COMMENT '参考来源',
  `sort_order`        INT          NOT NULL DEFAULT 0 COMMENT '排序',
  `status`            TINYINT      NOT NULL DEFAULT 1 COMMENT '状态 1启用 0停用',
  `create_time`       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time`       DATETIME     NULL     DEFAULT NULL COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_plan_code` (`plan_code`),
  KEY `idx_age_node_category` (`age_node`, `guidance_category`),
  KEY `idx_age_months` (`age_months_min`, `age_months_max`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='专家指导方案（72套预置数据）';

